@app.get("/api/values/{filename}/{column}")
async def get_unique_values(filename: str, column: str):
    conn = get_db_con()
    try:
        table_path = f'sources."{filename}"'
        query = f"""
            SELECT "{column}" as val, COUNT(*)::BIGINT as freq 
            FROM {table_path} 
            WHERE "{column}" IS NOT NULL 
            GROUP BY 1 
            ORDER BY freq DESC 
            LIMIT 100
        """
        df = conn.execute(query).df()
        
        # SOLUCIÓN: Reemplazar NaN e Infinitos por None (null en JSON)
        df = df.replace([np.inf, -np.inf], np.nan).where(df.notnull(), None)
        
        return df.to_dict(orient="records")
    except Exception as e:
        print(f"Error: {e}")
        raise HTTPException(status_code=500, detail=str(e))
    finally:
        conn.close()

