@app.get("/api/catalog-distinct-values/{filename}/{column}")
async def get_catalog_distinct(filename: str, column: str, search: str = None, page: int = 0):
    conn = get_db_con()
    page_size = 50
    offset = page * page_size
    
    try:
        table_path = f'catalogs."{filename}"'
        
        # Seleccionamos todas las columnas pero aseguramos unicidad en la columna técnica
        # Usamos FIRST() para las demás columnas para obtener una descripción representativa
        sql = f'SELECT * FROM {table_path}'
        
        # Filtro de búsqueda en cualquier columna
        if search:
            # Obtenemos las columnas para buscar en todas
            cols_info = conn.execute(f"PRAGMA table_info({table_path})").fetchall()
            search_targets = [f"CAST(\"{c[1]}\" AS VARCHAR) ILIKE '%{search}%'" for c in cols_info]
            sql += f" WHERE ({' OR '.join(search_targets)})"
        
        # Agrupamos por la columna técnica para que sea realmente un listado de códigos únicos
        sql += f' GROUP BY ALL ORDER BY "{column}" ASC LIMIT {page_size} OFFSET {offset}'
        
        df = conn.execute(sql).df()
        df = df.astype(object).replace({np.nan: None})
        
        return df.to_dict(orient="records")
    except Exception as e:
        print(f"Error: {e}")
        raise HTTPException(status_code=500, detail=str(e))
    finally:
        conn.close()


@app.post("/api/auto-map-values")
async def auto_map_values(data: dict):
    # data contiene: source_file, source_col, catalog_file, catalog_col
    conn = get_db_con()
    try:
        s_file = data['source_file']
        s_col = data['source_col']
        c_file = data['catalog_file']
        c_col = data['catalog_col']

        # Query que busca coincidencias exactas entre ambos esquemas
        query = f"""
            SELECT DISTINCT 
                s."{s_col}" as source_val, 
                c."{c_col}" as target_val
            FROM sources."{s_file}" s
            JOIN catalogs."{c_file}" c ON CAST(s."{s_col}" AS VARCHAR) = CAST(c."{c_col}" AS VARCHAR)
            WHERE s."{s_col}" IS NOT NULL
        """
        
        results = conn.execute(query).df()
        # Convertimos a un diccionario simple { "valor_origen": "valor_catalogo" }
        mapping_result = dict(zip(results['source_val'], results['target_val']))
        
        return mapping_result
    finally:
        conn.close()

