@app.get("/api/memoryusage")
def get_memory_usage():
    try:
        mem = psutil.virtual_memory()
        total_gb = mem.total / (1024 ** 3)
        available_gb = mem.available / (1024 ** 3)
        used_gb = total_gb - available_gb
        
        return {
            "percentage": mem.percent,
            "total_gb": round(total_gb, 2),
            "used_gb": round(used_gb, 2),
            "text": f"{round(used_gb, 2)} / {round(total_gb, 2)} GB",
            "status": "online"
        }
    except Exception as e:
        # Si algo falla, devolvemos valores neutros para no romper el front
        print(f"Error reading system memory: {e}")
        return {
            "percentage": 0,
            "total_gb": 0,
            "used_gb": 0,
            "text": "N/A",
            "status": "error"
        }
        
@app.post("/api/detect-date-format")
async def api_detect_date_format(data: dict):
    try:
        conn = get_db_con()

        file_name = data.get('file')
        col_name = data.get('column')
        
        # Lista de formatos candidatos
        formats = [
            # --- DATETIME (Con segundos y milisegundos) ---
            '%Y-%m-%d %H:%M:%S.%f',  # ISO con milisegundos (2023-10-25 14:30:00.123)
            '%Y-%m-%dT%H:%M:%S',     # ISO 8601 con T (2023-10-25T14:30:00)
            '%Y-%m-%d %H:%M:%S',     # ISO Estándar
            '%d/%m/%Y %H:%M:%S',     # Europeo con segundos (25/10/2023 14:30:00)
            '%m/%d/%Y %H:%M:%S',     # Americano con segundos (10/25/2023 14:30:00)
            
            # --- DATETIME (Sin segundos) ---
            '%d/%m/%Y %H:%M',        # Europeo común
            '%m/%d/%Y %H:%M',        # Americano común
            '%d-%m-%Y %H:%M',        # Europeo con guiones
            '%Y%m%d%H%M%S',          # Todo pegado largo (20231025143000)
            
            # --- DATE (Formatos de 8 o más caracteres) ---
            '%d/%m/%Y',              # Europeo (25/10/2023)
            '%m/%d/%Y',              # Americano (10/25/2023)
            '%Y-%m-%d',              # ISO Date
            '%d-%m-%Y',              # Europeo con guiones
            '%m-%d-%Y',              # Americano con guiones
            '%d.%m.%Y',              # Alemán/Centro-europeo (25.10.2023)
            
            # --- DATE (Formatos pegados / compactos) ---
            '%Y%m%d',                # ISO pegado (20231025)
            '%d%m%Y',                # Europeo pegado (25102023)
            '%m%d%Y',                # Americano pegado (10252023)
            
            # --- CASOS DE 2 DÍGITOS (Año al final) ---
            '%d/%m/%y',              # 25/10/23
            '%m/%d/%y',              # 10/25/23
            '%y%m%d'                 # 231025
        ]

        try:
            # 1. Obtenemos la muestra (Fix: CAST a VARCHAR para evitar el Binder Error)
            query = f"""
                SELECT DISTINCT "{col_name}"::VARCHAR 
                FROM sources."{file_name}" 
                WHERE "{col_name}" IS NOT NULL 
                AND TRIM("{col_name}"::VARCHAR) NOT IN ('', 'NaN', 'null', 'NULL')
                LIMIT 50
            """
            samples = [r[0] for r in conn.execute(query).fetchall()]
            
            if not samples:
                return {"format": None}

            # 2. Probamos cada formato
            for fmt in formats:
                try:
                    # Reemplazamos 99 por 00 virtualmente y probamos el parseo
                    # Usamos samples (la variable correcta) y la pasamos como literal de lista
                    # Dentro de tu bucle for fmt in formats:
                    test_sql = f"""
                        SELECT COUNT(*) 
                        FROM (SELECT unnest({samples}) as v)
                        WHERE TRY_CAST(
                            strptime(
                                regexp_replace(TRIM(v), '99', '00', 'g'), 
                                '{fmt}'
                            ) AS TIMESTAMP
                        ) IS NOT NULL
                    """
                    valid_count = conn.execute(test_sql).fetchone()[0]
                    
                    # Si todos los valores de la muestra son válidos con este formato, lo encontramos
                    if valid_count == len(samples):
                        return {"format": fmt}
                except:
                    continue

            return {"format": None}

        except Exception as e:
            print(f"Error interno en la detección: {str(e)}")
            return {"format": None, "error": str(e)}

    finally:
        # Importante: cerrar la conexión si no usas un context manager
        conn.close()

