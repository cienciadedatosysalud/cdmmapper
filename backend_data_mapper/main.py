                alias = "T1" if source_file == t1_name else "T2"

                if is_join:
                    cond_sql = " AND ".join([f"CAST(T1.\"{c['left']}\" AS VARCHAR) = CAST(T2.\"{c['right']}\" AS VARCHAR)" for c in join_info['conditions']])
