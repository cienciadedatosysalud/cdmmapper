@app.post("/api/ingest-single-source")
async def ingest_source(file: UploadFile = File(...)):
    conn = get_db_con()
    try:
        filename = file.filename
        save_path = os.path.join(RAW_DIR, filename)
        
        # Guardar CSV físico
        with open(save_path, "wb") as buffer:
            shutil.copyfileobj(file.file, buffer)
        
        # Insertar en esquema 'sources' usando comillas dobles
        table_path = f'sources."{filename}"'
        conn.execute(f"CREATE OR REPLACE TABLE {table_path} AS SELECT * FROM read_csv_auto('{save_path}', nullstr=['', 'NA'])")
        
        # Metadatos
        res = conn.execute(f"SELECT COUNT(*)::BIGINT FROM {table_path}").fetchone()
        row_count = res[0] if res else 0
        
        # Obtener columnas con DESCRIBE
        cols_res = conn.execute(f"DESCRIBE {table_path}").fetchall()
        columns = [{"name": r[0], "type": str(r[1])} for r in cols_res]
        
        return {"name": filename, "rows": row_count, "cols": columns}
    except Exception as e:
        raise HTTPException(status_code=500, detail=f"Error en fuente {filename}: {str(e)}")
    finally:
        conn.close()


